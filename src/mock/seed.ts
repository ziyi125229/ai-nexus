function hash(n: number): number {
  const x = Math.sin(n * 12.9898) * 43758.5453;
  return x - Math.floor(x);
}

export function buildDailyMetrics(): DailyMetric[] {
  return Array.from({ length: 30 }, (_, i) => {
    const daysAgo = 29 - i;
    const wave = 0.78 + hash(i + 3) * 0.35 + (i > 22 ? 0.12 : 0);
    const weekend = new Date(NOW.getTime() - daysAgo * 86400000).getDay();
    const weekendFactor = weekend === 0 || weekend === 6 ? 0.62 : 1;
    const calls = Math.round(38200 * wave * weekendFactor);
    const tokens = Math.round(calls * 620);
    const cost = Number((tokens / 1000) * 0.0078);
    const successRate = Number((99.05 + hash(i + 9) * 0.7 - (i === 26 ? 1.4 : 0)).toFixed(2));
    const latencyP95 = Math.round(980 + hash(i + 4) * 420 + (i === 26 ? 700 : 0));
    return {
      date: iso(daysAgo, 0, 0).slice(0, 10),
      calls,
      tokens,
      cost: Number(cost.toFixed(2)),
      successRate,
      latencyP95,
    };
  });
}

