const NOW = new Date("2026-10-30T11:00:00+08:00");

function iso(daysAgo: number, hour = 10, minute = 0): string {
  const d = new Date(NOW);
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

