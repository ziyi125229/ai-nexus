export function createSeedStore(): StoreState {
  const traceLogs = traces.map((trace) => ({
    id: trace.logId ?? `log-${trace.id}`,
    time: trace.startAt,
    appId: trace.appId,
    modelId: trace.modelId,
    agentId: trace.agentId,
    status: trace.status,
    latency: trace.durationMs,
    inputTokens: 800,
    outputTokens: trace.status === "success" ? 260 : 0,
    cost: 0.012,
    requestId: trace.requestId,
    traceId: trace.id,
    prompt: trace.prompt,
    output: trace.output,
    errorCode: trace.status === "timeout" ? "GATEWAY_TIMEOUT" : trace.status === "error" ? "TOOL_ERROR" : undefined,
    errorMessage: trace.spans.find((span) => span.status !== "success")?.detail,
  }));
  return {
    models,
    datasets,
    tools,
    agents,
    apps,
    credentials,
    logs: [...traceLogs, ...buildLogs()],
    alerts,
    traces: traces.map((trace) => ({
      ...trace,
      spans: trace.spans.map((span) => ({
        ...span,
        startedAt: span.startedAt ?? trace.startAt,
        inputSummary: span.inputSummary ?? trace.prompt,
        outputSummary: span.outputSummary ?? span.detail,
        errorMessage: span.errorMessage ?? (span.status === "success" ? undefined : span.detail),
      })),
    })),
    users,
    audits,
    notifications,
    settings,
    playgroundHistory: [],
    dailyMetrics: buildDailyMetrics(),
  };
}
